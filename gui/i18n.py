_current: dict[str, str] = TRANSLATIONS[ZH]


def set_language(lang: str) -> None:
    global _current
    # An unknown language code falls back to English (not to Simplified Chinese)
    _current = TRANSLATIONS.get(lang) or TRANSLATIONS[EN]
    # Sync the core library language (error messages in the launcher package)
    from launcher.i18n import set_core_language

    set_core_language(current_language())


    install_qt_translations(lang)

def current_language() -> str:
    for lang, table in TRANSLATIONS.items():
        if table is _current:
            return lang
    return ZH


def tr(key: str, *args) -> str:
    template = _current.get(key)
    if template is None:
        # A key missing from the active language resolves to English, never to
        # Simplified Chinese: a user on a non-Chinese interface must not suddenly
        # see Chinese text. Only if English lacks the key too is the key shown.
        template = TRANSLATIONS[EN].get(key, key)
    if args:
        return template.format(*args)
    return template


UI_LANGUAGES: list[tuple[str, str]] = [
    ("zh_cn", "简体中文"),
    ("zh_tw", "繁體中文"),
    ("en_us", "English"),
    ("ja_jp", "日本語"),
    ("ko_kr", "한국어"),
    ("ru_ru", "Русский"),
    ("fr_fr", "Français"),
    ("es_es", "Español"),
    ("de_de", "Deutsch"),
]


def detect_system_language(locale_name: str | None = None) -> str:
    """按系统区域返回受支持的启动器语言码；无匹配时回退英文。

    精确匹配优先（zh_TW -> zh_tw），其次按语言前缀匹配（en_GB -> en_us）。
    识别不出来时回落 `en_us`，**不回退简体中文**（非中文用户不该突然看到中文）。
    """
    if locale_name is None:
        try:
            from PySide6.QtCore import QLocale

            locale_name = QLocale.system().name()
        except Exception:  # noqa: BLE001 - fall back to the default language if detection fails
            locale_name = ""
    norm = (locale_name or "").replace("-", "_").lower()
    if not norm:
        # Locale detection failed entirely: fall back to English, never to Chinese
        # (and never let an empty prefix match every language below).
        return EN
    # Region aliases: HK/MO use Traditional Chinese
    aliases = {"zh_hk": "zh_tw", "zh_mo": "zh_tw"}
    if norm in aliases:
        return aliases[norm]
    supported = {code for code, _name in UI_LANGUAGES}
    if norm in supported:
        return norm
    prefix = norm.split("_")[0]
    if prefix:
        for code, _name in UI_LANGUAGES:
            if code.startswith(prefix):
                return code
    return EN


